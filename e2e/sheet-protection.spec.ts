// A protected sheet in the editor: typing into a locked cell is refused with a message (and
// nothing is written), an unlocked cell takes what is typed; Delete and paste over locked
// cells are refused; the buttons of formats, merging, sorting, the filter, rules and charts are
// off and say why in their titles, and so are the items of the menus of cells and headers; a
// formula the protection hides is not shown in the formula bar. The menu of a tab protects the
// sheet and removes its protection (asking for the password of one that has a password). A
// workbook whose structure is locked adds, moves and renames no sheet.
//
// No screenshots. Every workbook is generated by code.
import type { Page } from '@playwright/test';
import { buildXlsx, worksheetXml } from '../test/fixtures';
import { expect, test } from './helpers';

const STYLES =
  '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">' +
  '<fonts count="1"><font><sz val="11"/><name val="Calibri"/></font></fonts><fills count="2"><fill><patternFill patternType="none"/></fill><fill><patternFill patternType="gray125"/></fill></fills>' +
  '<borders count="1"><border/></borders><cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs>' +
  '<cellXfs count="3"><xf numFmtId="0" fontId="0" fillId="0" borderId="0" xfId="0"/>' +
  '<xf numFmtId="0" fontId="0" fillId="0" borderId="0" xfId="0" applyProtection="1"><protection locked="0"/></xf>' +
  '<xf numFmtId="0" fontId="0" fillId="0" borderId="0" xfId="0" applyProtection="1"><protection hidden="1"/></xf></cellXfs>' +
  '</styleSheet>';

/** A1 locked (1), B1 unlocked (2), C1 a hidden formula =1+2; the sheet protected as given. */
const protectedBook = (protection = '<sheetProtection sheet="1" objects="1" scenarios="1"/>', head = '') =>
  buildXlsx({
    styles: STYLES,
    workbookHead: head,
    sheets: [
      {
        name: 'Data',
        xml: worksheetXml(`<sheetData><row r="1"><c r="A1"><v>1</v></c><c r="B1" s="1"><v>2</v></c><c r="C1" s="2"><f>1+2</f><v>3</v></c></row></sheetData>${protection}`),
      },
      { name: 'Other', xml: worksheetXml('<sheetData/>') },
    ],
  });

async function mount(page: Page, bytes: Uint8Array, options: Record<string, unknown> = {}): Promise<void> {
  await page.goto('/e2e/pages/editor.html');
  await page.waitForFunction(() => typeof (window as any).__mountEditor === 'function');
  await page.evaluate(
    async ({ base64, options }) => {
      const text = atob(base64);
      const data = new Uint8Array(text.length);
      for (let i = 0; i < text.length; i++) data[i] = text.charCodeAt(i);
      await (window as any).__mountEditor(data, options, 'host');
    },
    { base64: Buffer.from(bytes).toString('base64'), options: { locale: 'en-US', ...options } },
  );
  await expect(page.locator('#host .bym-canvas')).toBeVisible();
}

const view = (page: Page, code: string) => page.evaluate((code) => new Function('view', 'api', `return ${code}`)((window as any).__editor.view, (window as any).BymOffice), code);
const live = (page: Page) => page.locator('#host .bym-live');
const command = (page: Page, name: string) => page.locator(`#host [data-command="${name}"]`);
const value = (page: Page, row: number, col: number) => view(page, `(api.getCell(view.workbook.sheets[0], ${row}, ${col}) || {}).value`);
const LOCKED = 'The cell or range is on a protected sheet. To change it, remove the protection of the sheet (a password may be asked for)';

async function select(page: Page, cell: string): Promise<void> {
  await view(page, `view.select(api.parseRange('${cell}'))`);
}

test.describe('protected sheet', () => {
  test('a locked cell takes nothing that is typed and says why; an unlocked cell takes it', async ({ page }) => {
    await mount(page, await protectedBook());
    await select(page, 'A1');
    await view(page, 'view.focus()');
    await page.keyboard.type('9');
    await expect(live(page)).toHaveText(LOCKED);
    expect(await view(page, 'view.isEditing')).toBe(false);
    expect(await value(page, 0, 0)).toBe(1);
    // F2 and a call of the application are refused the same way.
    await page.keyboard.press('F2');
    expect(await view(page, 'view.isEditing')).toBe(false);
    await view(page, 'view.startEditing()');
    expect(await view(page, 'view.isEditing')).toBe(false);

    await select(page, 'B1');
    await view(page, 'view.focus()');
    await page.keyboard.type('7');
    await page.keyboard.press('Enter');
    expect(await value(page, 0, 1)).toBe(7);
  });

  test('Delete and paste over a locked cell are refused; the workbook stays as it was', async ({ page }) => {
    await mount(page, await protectedBook());
    await select(page, 'A1:B1');
    await view(page, 'view.focus()');
    await page.keyboard.press('Delete');
    await expect(live(page)).toHaveText(LOCKED);
    expect(await value(page, 0, 0)).toBe(1);
    expect(await value(page, 0, 1)).toBe(2);
    await view(page, `(() => { try { view.paste('5\\t6'); return 'pasted'; } catch (error) { return error.code; } })()`).then((outcome) => expect(outcome).toBe('protected'));
    expect(await value(page, 0, 0)).toBe(1);
    expect(await view(page, 'view.canUndo')).toBe(false);
  });

  test('a refused step leaves no format behind: the file is saved as it was read', async ({ page }) => {
    const bytes = await protectedBook();
    await mount(page, bytes);
    // "50%" would bring a percentage format; A1 is locked.
    expect(await view(page, `(() => { try { view.setCellInput(0, 0, '50%'); return 'written'; } catch (error) { return error.code; } })()`)).toBe('protected');
    const same = await page.evaluate(async (original) => {
      const saved: Uint8Array = await (window as any).__file.save();
      return saved.length === original.length && saved.every((byte, index) => byte === original[index]);
    }, Array.from(bytes));
    expect(same).toBe(true);
  });

  test('the buttons of what the protection forbids are off and say why', async ({ page }) => {
    await mount(page, await protectedBook());
    for (const name of ['bold', 'fillColor', 'merge', 'sortAscending', 'filter', 'validation', 'conditionalFormat', 'chart']) {
      await expect(command(page, name)).toBeDisabled();
      await expect(command(page, name)).toHaveAttribute('title', /^The sheet is protected/);
    }
    // The page setup and the frozen panes stay.
    await expect(command(page, 'pageSetup')).toBeEnabled();
    await expect(command(page, 'rowsColumns')).toBeEnabled();
    // On the other sheet, which is not protected, everything is on again.
    await view(page, 'view.setActiveSheet(1)');
    await expect(command(page, 'bold')).toBeEnabled();
    await expect(command(page, 'bold')).not.toHaveAttribute('title', /protected/);
  });

  test('a sheet that allows formats has its format buttons on', async ({ page }) => {
    await mount(page, await protectedBook('<sheetProtection sheet="1" formatCells="0"/>'));
    await expect(command(page, 'bold')).toBeEnabled();
    await expect(command(page, 'merge')).toBeEnabled();
    await expect(command(page, 'sortAscending')).toBeDisabled();
    await select(page, 'A1');
    await view(page, 'view.format({ bold: true })');
    expect(await view(page, '(() => { const styles = view.workbook.styles; return styles.fonts[styles.cellXfs[api.getCell(view.workbook.sheets[0], 0, 0).style].fontId].bold; })()')).toBe(true);
  });

  test('the menu of a cell turns off what the protection forbids, and an item that is off says why', async ({ page }) => {
    await mount(page, await protectedBook());
    const box = (await page.locator('#host .bym-canvas').boundingBox())!;
    // A1: 72 pixels of row header, 22 of column header.
    await page.mouse.click(box.x + 72 + 20, box.y + 22 + 10, { button: 'right' });
    const menu = page.locator('#host .bym-menu');
    await expect(menu).toBeVisible();
    const item = (label: string) => menu.locator('.bym-menu-item', { hasText: label });
    await expect(item('Cut')).toHaveAttribute('aria-disabled', 'true');
    await expect(item('Clear contents')).toHaveAttribute('aria-disabled', 'true');
    await expect(item('Insert row above')).toHaveAttribute('aria-disabled', 'true');
    await expect(item('Delete row')).toHaveAttribute('aria-disabled', 'true');
    await expect(item('Copy')).not.toHaveAttribute('aria-disabled', 'true');
    // The item is off (aria-disabled): Playwright would wait for it to be enabled. Chosen all the same, it says why.
    await item('Clear contents').click({ force: true });
    await expect(live(page)).toHaveText(LOCKED);
  });

  test('a formula the protection hides is not in the formula bar; its value is in the cell', async ({ page }) => {
    await mount(page, await protectedBook());
    await select(page, 'C1');
    expect(await view(page, 'view.editText')).toBe('');
    // Nor is it in the hidden input the keys go to.
    expect(await page.locator('#host .bym-input').inputValue()).not.toContain('1+2');
    expect(await value(page, 0, 2)).toBe(3);
    await view(page, 'view.unprotectSheet()');
    expect(await view(page, 'view.editText')).toBe('=1+2');
  });

  test('the menu of a tab protects the sheet and removes the protection; undo puts it back', async ({ page, hasTouch }) => {
    test.skip(hasTouch, 'a right click is needed');
    await mount(page, await protectedBook(''));
    const tab = page.locator('#host .bym-tab', { hasText: 'Data' });
    await tab.click({ button: 'right' });
    const menu = page.locator('#host .bym-menu');
    await menu.locator('.bym-menu-item', { hasText: 'Protect sheet' }).click();
    await expect.poll(() => view(page, 'view.isSheetProtected(0)')).toBe(true);
    await expect(command(page, 'bold')).toBeDisabled();
    await tab.click({ button: 'right' });
    await menu.locator('.bym-menu-item', { hasText: 'Unprotect sheet' }).click();
    await expect.poll(() => view(page, 'view.isSheetProtected(0)')).toBe(false);
    await view(page, 'view.undo()');
    expect(await view(page, 'view.isSheetProtected(0)')).toBe(true);
  });

  test('a protection with a password asks for it, says when it is wrong, and goes with the right one', async ({ page, hasTouch }) => {
    test.skip(hasTouch, 'a right click is needed');
    // The legacy hash of "secret".
    await mount(page, await protectedBook('<sheetProtection password="DAA7" sheet="1"/>'));
    const tab = page.locator('#host .bym-tab', { hasText: 'Data' });
    await tab.click({ button: 'right' });
    await page.locator('#host .bym-menu .bym-menu-item', { hasText: 'Unprotect sheet' }).click();
    const field = page.locator('[data-bym-field="password"]');
    await expect(field).toBeFocused();
    await field.fill('wrong');
    await page.keyboard.press('Enter');
    await expect(page.locator('.bym-password-message')).toHaveText('The password is not correct.');
    expect(await view(page, 'view.isSheetProtected(0)')).toBe(true);
    await field.fill('secret');
    await page.keyboard.press('Enter');
    await expect.poll(() => view(page, 'view.isSheetProtected(0)')).toBe(false);
    await expect(page.locator('[data-bym-dialog="password"]')).toHaveCount(0);
    // Through the API: a wrong password is refused with its code.
    await mount(page, await protectedBook('<sheetProtection password="DAA7" sheet="1"/>'));
    expect(await view(page, `view.unprotectSheet(0, 'nope').then(() => 'done', (error) => error.code)`)).toBe('wrong-password');
    expect(await view(page, `view.unprotectSheet(0, 'secret')`)).toBe(true);
  });

  test('a saved file keeps the protection; one unprotected is saved without it', async ({ page }) => {
    await mount(page, await protectedBook());
    await view(page, 'view.unprotectSheet()');
    const saved = await page.evaluate(async () => {
      const bytes = await (window as any).__file.save();
      const file = await (window as any).BymOffice.open(bytes);
      const book = await file.workbook();
      return (window as any).BymOffice.sheetProtected(book.sheets[0]);
    });
    expect(saved).toBe(false);
  });
});

test.describe('protected structure', () => {
  test('no sheet is added, renamed or moved; the add button is off and says why', async ({ page }) => {
    await mount(page, await protectedBook('', '<workbookProtection lockStructure="1"/>'));
    const add = page.locator('#host .bym-tab-add');
    await expect(add).toBeDisabled();
    await expect(add).toHaveAttribute('title', /^The structure of the workbook is protected/);
    expect(await view(page, `(() => { try { view.insertSheet(); return 'inserted'; } catch (error) { return error.code; } })()`)).toBe('protected');
    expect(await view(page, `(() => { try { view.renameSheet(0, 'X'); return 'renamed'; } catch (error) { return error.message; } })()`)).toMatch(/structure of the workbook is protected/);
    expect(await view(page, 'view.workbook.sheets.map((sheet) => sheet.name).join()')).toBe('Data,Other');
  });
});
