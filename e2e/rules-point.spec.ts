async function mount(page: Page, bytes: Uint8Array, options: Record<string, unknown> = {}): Promise<void> {
  await page.goto('/e2e/pages/editor.html');
  await page.waitForFunction(() => typeof (window as any).__mountEditor === 'function');
  await page.evaluate(
    async ({ base64, options }) => {
      const text = atob(base64);
      const data = new Uint8Array(text.length);
      for (let i = 0; i < text.length; i++) data[i] = text.charCodeAt(i);
      await (window as any).__mountEditor(data, options, 'host');
    },
    { base64: Buffer.from(bytes).toString('base64'), options: { locale: 'en-US', ...options } },
  );
  await expect(page.locator('#host .bym-canvas')).toBeVisible();
}

const view = <T = unknown>(page: Page, code: string): Promise<T> =>
  page.evaluate((code) => new Function('view', 'api', `return ${code}`)((window as any).__editor.view, (window as any).BymOffice), code) as Promise<T>;
const select = (page: Page, ref: string) => view(page, `(view.select(api.parseRange(${JSON.stringify(ref)})), view.focus(), true)`);
const selection = (page: Page) => view<string>(page, 'api.rangeName(view.selection.range)');
const shownSheet = (page: Page) => view<number>(page, 'view.activeSheet');
const dialog = (page: Page, name: string) => page.locator(`#host [data-bym-dialog="${name}"]`);
const field = (page: Page, of: string, name: string) => dialog(page, of).locator(`[data-bym-field="${name}"]`).first();
const action = (page: Page, of: string, name: string) => dialog(page, of).locator(`[data-bym-action="${name}"]`).first();
const alert = (page: Page, of: string) => dialog(page, of).locator('[role="alert"]');
const changes = (page: Page) => page.evaluate(() => (window as any).__events.filter((event: { type: string }) => event.type === 'change').length as number);
const focusedField = (page: Page) => page.evaluate(() => (document.activeElement ? document.activeElement.getAttribute('data-bym-field') || document.activeElement.getAttribute('data-bym-action') || document.activeElement.className : ''));
const caret = (page: Page) =>
  page.evaluate(() => {
    const el = document.activeElement as HTMLInputElement;
    return [el.selectionStart, el.selectionEnd, el.value.length];
  });

const rules = (page: Page) =>
  page.evaluate(() => {
    const api = (window as any).BymOffice;
    return (window as any).__editor.view.conditionalRules().map((info: any) => {
      const rule = info.rule;
      return `${info.ranges.map(api.rangeName).join(' ')}|${rule.type}|${(rule.formulas || []).join(';')}`;
    });
  });

/** The rule of a cell as the view applies it: "ranges|type|formula1|formula2", or null. */
const validationAt = (page: Page, ref: string) =>
  page.evaluate((ref) => {
    const api = (window as any).BymOffice;
    const at = api.parseCellRef(ref);
    const rule = (window as any).__editor.view.validationAt(at.row, at.col);
    return rule ? `${rule.ranges.map(api.rangeName).join(' ')}|${rule.type}|${rule.formula1 ?? ''}|${rule.formula2 ?? ''}` : null;
  }, ref);

/** Saves the workbook and shows what was saved in the editor again. */
async function reopen(page: Page): Promise<void> {
  const saved = await page.evaluate(async () => Array.from((await (window as any).__file.save()) as Uint8Array));
  await mount(page, new Uint8Array(saved));
}

type Box = { x: number; y: number; width: number; height: number };
const canvasBox = async (page: Page): Promise<Box> => (await page.locator('#host .bym-canvas').boundingBox())!;

/** The middle of a cell (0-based row and column) of an unscrolled sheet with default sizes. */
async function cell(page: Page, row: number, col: number): Promise<{ x: number; y: number }> {
  const box = await canvasBox(page);
  return { x: box.x + HEADER_WIDTH + COLUMN_WIDTH * (col + 0.5), y: box.y + HEADER_HEIGHT + ROW_HEIGHT * (row + 0.5) };
}

/** What a press at a point of the page lands on: "backdrop" for the place beside a dialog. */
const under = (page: Page, at: { x: number; y: number }) =>
  page.evaluate(([x, y]) => {
    const el = document.elementFromPoint(x, y);
    return el ? (el.classList.contains('bym-dialog-backdrop') ? 'backdrop' : el.className || el.tagName) : 'nothing';
  }, [at.x, at.y]);

/** A click of the mouse on a cell behind the dialog. */
async function clickCell(page: Page, row: number, col: number, modifiers: string[] = []): Promise<void> {
  const at = await cell(page, row, col);
  expect(await under(page, at), `cell ${row},${col} is beside the dialog`).toBe('backdrop');
  for (const key of modifiers) await page.keyboard.down(key);
  await page.mouse.click(at.x, at.y);
  for (const key of modifiers) await page.keyboard.up(key);
}

/** A drag of the mouse from one cell to another; `during` runs while the button is held at the end of it. */
async function dragCells(page: Page, from: [number, number], to: [number, number], modifiers: string[] = [], during?: () => Promise<void>): Promise<void> {
  const a = await cell(page, from[0], from[1]);
  const b = await cell(page, to[0], to[1]);
  expect(await under(page, a), 'the drag begins beside the dialog').toBe('backdrop');
  for (const key of modifiers) await page.keyboard.down(key);
  await page.mouse.move(a.x, a.y);
  await page.mouse.down();
  await page.mouse.move((a.x + b.x) / 2, (a.y + b.y) / 2, { steps: 3 });
  await page.mouse.move(b.x, b.y, { steps: 3 });
  if (during) await during();
  await page.mouse.up();
  for (const key of modifiers) await page.keyboard.up(key);
}

/** A click of the mouse on the tab of a sheet, which the dialog covers. */
async function clickTab(page: Page, name: string): Promise<void> {
  const box = (await page.locator('#host .bym-tab', { hasText: name }).boundingBox())!;
  const at = { x: box.x + box.width / 2, y: box.y + box.height / 2 };
  expect(await under(page, at), `the tab ${name} is beside the dialog`).toBe('backdrop');
  await page.mouse.click(at.x, at.y);
}

const sheetEvents = (page: Page) => page.evaluate(() => (window as any).__events.filter((event: { type: string }) => event.type === 'sheet').map((event: { sheet: number }) => event.sheet) as number[]);
const cellOf = (page: Page, sheet: number, ref: string) =>
  page.evaluate(
    ([sheet, ref]) => {
      const api = (window as any).BymOffice;
      const at = api.parseCellRef(ref);
      const found = api.getCell((window as any).__editor.view.workbook.sheets[sheet as number], at.row, at.col);
      return found ? found.value : null;
    },
    [sheet, ref] as [number, string],
  );
const pointing = (page: Page, name: string) => dialog(page, name).evaluate((el) => el.hasAttribute('data-bym-pointing'));

/** Presses the mouse on a cell behind the dialog and holds it; gives back the id the browser gave the pointer. */
async function holdCell(page: Page, row: number, col: number): Promise<number> {
  const at = await cell(page, row, col);
  expect(await under(page, at), 'the press is beside the dialog').toBe('backdrop');
  await page.evaluate(() => {
    document.querySelector('#host .bym-dialog-backdrop')!.addEventListener('pointerdown', (event) => ((window as any).__pointerId = (event as PointerEvent).pointerId), { once: true, capture: true });
  });
  await page.mouse.move(at.x, at.y);
  await page.mouse.down();
  return page.evaluate(() => (window as any).__pointerId as number);
}

/** A pointer event made by a script on the place beside the dialog, at the middle of a cell. */
async function backdropEvent(page: Page, type: string, pointerId: number, row: number, col: number, buttons: number): Promise<void> {
  const at = await cell(page, row, col);
  await page.evaluate(
    ([type, id, x, y, buttons]) => {
      document
        .querySelector('#host .bym-dialog-backdrop')!
        .dispatchEvent(new PointerEvent(type as string, { pointerId: id as number, pointerType: 'mouse', isPrimary: true, clientX: x as number, clientY: y as number, buttons: buttons as number, bubbles: true, cancelable: true }));
    },
    [type, pointerId, at.x, at.y, buttons] as [string, number, number, number, number],
  );
}

/** How many pixels along the top edge of a cell have the colour of the frame around a reference. */
function framePixels(page: Page, row: number, col: number): Promise<number> {
  return page.evaluate(
    ([x, y, width]) => {
      (window as any).__editor.view.render();
      const canvas = document.querySelector('#host .bym-canvas') as HTMLCanvasElement;
      const ratio = canvas.width / canvas.clientWidth;
      const data = canvas.getContext('2d')!.getImageData(Math.round(x * ratio), Math.round(y * ratio), Math.round(width * ratio), 1).data;
      let found = 0;
      for (let i = 0; i < data.length; i += 4) if (data[i] < 90 && data[i + 1] < 160 && data[i + 2] > 180) found++;
      return found;
    },
    [HEADER_WIDTH + COLUMN_WIDTH * col, HEADER_HEIGHT + ROW_HEIGHT * row, COLUMN_WIDTH],
  );
}

