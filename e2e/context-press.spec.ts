// Ctrl and a click of the main button. On a device of Apple's that is the press that asks for
// the context menu: it is no click - it points at no cell for a formula that is being typed,
// selects nothing by dragging, and drags no tab - and the menu that comes with it does what it
// does after any such press. Everywhere else Ctrl and a click is a click.
//
// The view asks navigator.platform which of the two it is on; both answers are given to it
// here, whatever machine the tests run on. Whether the browser itself sends a `contextmenu`
// with the press is the machine's affair, and what is expected holds either way.
//
// Pointer positions are written out by hand from the default sizes of a sheet (header 72 x 22,
// columns 64 wide, rows 20 high). Every workbook is generated by code.
import type { Page } from '@playwright/test';
import { buildXlsx, worksheetXml } from '../test/fixtures';
import { expect, test } from './helpers';

const HEADER_WIDTH = 72;
const HEADER_HEIGHT = 22;
const COLUMN_WIDTH = 64;
const ROW_HEIGHT = 20;
const MOUSE_ONLY = 'mouse input is covered by the desktop projects';

const num = (ref: string, value: number) => `<c r="${ref}"><v>${value}</v></c>`;
const workbook = () =>
  buildXlsx({
    sheets: [
      { name: 'Data', xml: worksheetXml(`<sheetData><row r="1">${num('A1', 1)}${num('B1', 2)}</row><row r="2">${num('A2', 5)}${num('B2', 20)}</row></sheetData>`) },
      { name: 'Calc', xml: worksheetXml('<sheetData/>') },
      { name: 'Notes', xml: worksheetXml('<sheetData/>') },
    ],
  });

/** Mounts the workbook in a page that says it runs on `platform` (undefined: what the browser says itself). */
async function mountOn(page: Page, platform: string | undefined): Promise<boolean> {
  if (platform !== undefined) {
    await page.addInitScript((value) => {
      Object.defineProperty(Navigator.prototype, 'platform', { get: () => value, configurable: true });
    }, platform);
  }
  const bytes = await workbook();
  await page.goto('/e2e/pages/mount.html');
  await page.evaluate(async (input) => {
    const w = window as any;
    w.__notices = [];
    w.__mounted = await w.BymOffice.mount(document.getElementById('editor'), {
      file: new Uint8Array(input as number[]),
      locale: 'en-US',
      onNotice: (notice: any) => w.__notices.push({ message: notice.message, kind: notice.kind }),
    });
  }, Array.from(bytes));
  await expect(page.locator('.bym-canvas')).toBeVisible();
  const apple = await page.evaluate(() => /Mac|iPhone|iPad|iPod/.test(navigator.platform));
  if (platform !== undefined) expect(apple, `the page says it runs on ${platform}`).toBe(platform === 'MacIntel');
  return apple;
}

const view = <T>(page: Page, run: string): Promise<T> => page.evaluate(`(() => { const view = window.__mounted.view; const api = window.BymOffice; return ${run}; })()`) as Promise<T>;
const input = (page: Page) => page.locator('.bym-input');
const tab = (page: Page, name: string) => page.locator('.bym-tabs button', { hasText: name });
const sheetNames = (page: Page) => view<string[]>(page, 'view.workbook.sheets.map((sheet) => sheet.name)');
const selected = (page: Page) => view<string>(page, 'api.rangeName(view.selection.range)');
const formulaOf = (page: Page, ref: string) => view<string | undefined>(page, `(() => { const at = api.parseCellRef(${JSON.stringify(ref)}); const cell = api.getCell(view.workbook.sheets[0], at.row, at.col); return cell && cell.formula ? cell.formula.text : undefined; })()`);

async function cellPoint(page: Page, row: number, col: number): Promise<{ x: number; y: number }> {
  const box = (await page.locator('.bym-canvas').boundingBox())!;
  return { x: box.x + HEADER_WIDTH + COLUMN_WIDTH * (col + 0.5), y: box.y + HEADER_HEIGHT + ROW_HEIGHT * (row + 0.5) };
}

/** Ctrl held, the main button pressed at `from`, moved to `to` (when given) and let go. */
async function ctrlPress(page: Page, from: { x: number; y: number }, to?: { x: number; y: number }): Promise<void> {
  await page.mouse.move(from.x, from.y);
  await page.keyboard.down('Control');
  await page.mouse.down();
  if (to) await page.mouse.move(to.x, to.y, { steps: 8 });
  await page.mouse.up();
  await page.keyboard.up('Control');
}

/** Whatever menu the press opened is closed again. */
async function closeMenus(page: Page): Promise<void> {
  for (let i = 0; i < 3 && (await page.locator('.bym-menu').count()) > 0; i++) await page.keyboard.press('Escape');
}

async function typeIn(page: Page, ref: string, text: string): Promise<void> {
  await input(page).focus();
  await view(page, `(view.select(api.parseRange(${JSON.stringify(ref)})), true)`);
  await page.keyboard.type(text);
  await expect(input(page)).toHaveValue(text);
}

for (const platform of ['MacIntel', 'Win32', undefined]) {
  const named = platform === undefined ? 'the platform of the browser' : platform;

  test.describe(`Ctrl and a click on ${named}`, () => {
    test.beforeEach(({ hasTouch }) => {
      test.skip(!!hasTouch, MOUSE_ONLY);
    });

    test('while a formula is typed: no reference is written on a device of Apple, the cell is pointed at elsewhere', async ({ page }) => {
      const apple = await mountOn(page, platform);
      await typeIn(page, 'D1', '=5+');
      await ctrlPress(page, await cellPoint(page, 1, 1));
      // The menu that may have come with the press applied what was typed, where that can be applied.
      const state = () => view<{ editing: boolean; text: string }>(page, '({ editing: view.isEditing, text: view.isEditing ? view.editText : "" })');
      if (apple) {
        // Nothing was pointed at: the formula is what was typed, which cannot be applied as it stands.
        await expect.poll(state).toEqual({ editing: true, text: '=5+' });
        expect(await formulaOf(page, 'D1'), 'nothing was written into the cell').toBe(undefined);
        // No drag is left behind either: the pointer moves on and writes nothing.
        const away = await cellPoint(page, 3, 2);
        await page.mouse.move(away.x, away.y, { steps: 4 });
        expect((await state()).text).toBe('=5+');
      } else {
        await expect.poll(async () => ((await state()).editing ? (await state()).text : `=${await formulaOf(page, 'D1')}`)).toBe('=5+B2');
      }
      await closeMenus(page);
      await view(page, '(view.cancelEditing(), true)');
    });

    test('on the cells: nothing is selected by dragging on a device of Apple, a range elsewhere', async ({ page }) => {
      const apple = await mountOn(page, platform);
      await input(page).focus();
      await view(page, '(view.select(api.parseRange("A1")), true)');
      await ctrlPress(page, await cellPoint(page, 1, 1), await cellPoint(page, 3, 3));
      if (apple) {
        // The cell under the press may be chosen by the menu that came with it; a range is not dragged open.
        expect(await selected(page)).toMatch(/^(A1|B2)$/);
      } else {
        expect(await selected(page)).toBe('B2:D4');
      }
      await closeMenus(page);
    });

    test('on a tab: the tab is not dragged on a device of Apple, and is dragged elsewhere', async ({ page }) => {
      const apple = await mountOn(page, platform);
      const from = (await tab(page, 'Data').boundingBox())!;
      const to = (await tab(page, 'Notes').boundingBox())!;
      const start = { x: from.x + from.width / 2, y: from.y + from.height / 2 };
      const end = { x: to.x + to.width - 2, y: to.y + to.height / 2 };
      if (apple) await ctrlPress(page, start, end);
      else {
        // The events of the pointer alone: a machine of Apple's would send a `contextmenu` of its own with the press,
        // which no other machine does.
        await page.evaluate(
          ([x, y, toX]) => {
            const target = document.elementFromPoint(x, y)!;
            const strip = document.querySelector('.bym-tabs')!;
            const init = { clientY: y, button: 0, buttons: 1, ctrlKey: true, bubbles: true, cancelable: true, pointerId: 1, pointerType: 'mouse', isPrimary: true };
            target.dispatchEvent(new PointerEvent('pointerdown', { ...init, clientX: x }));
            for (let step = 1; step <= 8; step++) strip.dispatchEvent(new PointerEvent('pointermove', { ...init, clientX: x + ((toX - x) * step) / 8 }));
            strip.dispatchEvent(new PointerEvent('pointerup', { ...init, clientX: toX, buttons: 0 }));
          },
          [start.x, start.y, end.x],
        );
      }
      await closeMenus(page);
      if (apple) expect(await sheetNames(page)).toEqual(['Data', 'Calc', 'Notes']);
      else expect(await sheetNames(page)).toEqual(['Calc', 'Notes', 'Data']);
      expect(await view(page, 'view.history.canUndo'), 'a step only where the tab was dragged').toBe(!apple);
    });
  });
}

test.describe('the context menu after Ctrl and a click', () => {
  test.beforeEach(({ hasTouch }) => {
    test.skip(!!hasTouch, MOUSE_ONLY);
  });

  test('the menu of the cell opens for the `contextmenu` that comes with the press, and chooses the cell under it', async ({ page }) => {
    await mountOn(page, 'MacIntel');
    await input(page).focus();
    await view(page, '(view.select(api.parseRange("A1")), true)');
    const at = await cellPoint(page, 1, 1);
    // The press as a Mac sends it, with the event that asks for the menu: the same whatever the browser does by itself.
    await page.evaluate(
      ([x, y]) => {
        const canvas = document.querySelector('.bym-canvas')!;
        const init = { clientX: x, clientY: y, button: 0, buttons: 1, ctrlKey: true, bubbles: true, cancelable: true };
        canvas.dispatchEvent(new PointerEvent('pointerdown', { ...init, pointerId: 1, pointerType: 'mouse', isPrimary: true }));
        canvas.dispatchEvent(new MouseEvent('contextmenu', init));
        canvas.dispatchEvent(new PointerEvent('pointerup', { ...init, buttons: 0, pointerId: 1, pointerType: 'mouse', isPrimary: true }));
      },
      [at.x, at.y],
    );
    await expect(page.locator('.bym-menu')).toBeVisible();
    expect(await selected(page)).toBe('B2');
    await page.keyboard.press('Escape');
    await expect(page.locator('.bym-menu')).toHaveCount(0);
  });

  test('the menu of a tab opens the same way, and the tab stays where it is', async ({ page }) => {
    await mountOn(page, 'MacIntel');
    const box = (await tab(page, 'Calc').boundingBox())!;
    await page.evaluate(
      ([x, y]) => {
        const target = document.elementFromPoint(x, y)!;
        const init = { clientX: x, clientY: y, button: 0, buttons: 1, ctrlKey: true, bubbles: true, cancelable: true };
        target.dispatchEvent(new PointerEvent('pointerdown', { ...init, pointerId: 1, pointerType: 'mouse', isPrimary: true }));
        target.dispatchEvent(new MouseEvent('contextmenu', init));
        // The pointer goes on with the button down, as far as would drag a tab.
        target.dispatchEvent(new PointerEvent('pointermove', { ...init, clientX: x + 200, pointerId: 1, pointerType: 'mouse', isPrimary: true }));
        target.dispatchEvent(new PointerEvent('pointerup', { ...init, clientX: x + 200, buttons: 0, pointerId: 1, pointerType: 'mouse', isPrimary: true }));
      },
      [box.x + box.width / 2, box.y + box.height / 2],
    );
    await expect(page.locator('.bym-menu')).toBeVisible();
    expect(await view(page, 'view.activeSheet'), 'the tab is chosen, as by any press for its menu').toBe(1);
    await page.keyboard.press('Escape');
    expect(await sheetNames(page)).toEqual(['Data', 'Calc', 'Notes']);
    expect(await view(page, 'view.history.canUndo')).toBe(false);
  });
});
