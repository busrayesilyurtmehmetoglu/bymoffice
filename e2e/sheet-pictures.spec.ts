async function mount(page: Page, bytes: Uint8Array | number[], options: Record<string, unknown> = {}): Promise<void> {
  await page.goto('/e2e/pages/editor.html');
  await page.waitForFunction(() => typeof (window as any).__mountEditor === 'function');
  await page.evaluate(
    async ({ base64, options }) => {
      const text = atob(base64);
      const data = new Uint8Array(text.length);
      for (let i = 0; i < text.length; i++) data[i] = text.charCodeAt(i);
      await (window as any).__mountEditor(data, options, 'host');
    },
    { base64: Buffer.from(bytes as Uint8Array).toString('base64'), options: { locale: 'en-US', ...options } },
  );
  await expect(page.locator('#host .bym-canvas')).toBeVisible();
}

const view = (page: Page, code: string) => page.evaluate((code) => new Function('view', 'api', `return ${code}`)((window as any).__editor.view, (window as any).BymOffice), code);
const pictures = (page: Page): Promise<any[]> => view(page, 'view.pictures()') as Promise<any[]>;
const live = (page: Page) => page.locator('#host .bym-live');

/** Inserts PICTURE through the view at a cell; returns its id. */
function insert(page: Page, at: { row: number; col: number } = { row: 0, col: 0 }): Promise<number> {
  return page.evaluate(
    ({ bytes, at }) => (window as any).__editor.view.insertPicture(new Uint8Array(bytes), { at }),
    { bytes: Array.from(PICTURE), at },
  );
}

/** How many pixels of a colour a box of the canvas (CSS pixels) holds, after a forced redraw. */
function ink(page: Page, colour: number[], box: { x: number; y: number; width: number; height: number }): Promise<number> {
  return page.evaluate(
    ([colour, box]) => {
      const view = (window as any).__editor.view;
      view.render();
      const canvas = document.querySelector('#host .bym-canvas') as HTMLCanvasElement;
      const dpr = view.getViewState().devicePixelRatio;
      const area = box as { x: number; y: number; width: number; height: number };
      const width = Math.max(1, Math.round(area.width * dpr));
      const height = Math.max(1, Math.round(area.height * dpr));
      const data = canvas.getContext('2d')!.getImageData(Math.round(area.x * dpr), Math.round(area.y * dpr), width, height).data;
      const [r, g, b] = colour as number[];
      let count = 0;
      for (let at = 0; at < data.length; at += 4) if (Math.abs(data[at] - r) <= 4 && Math.abs(data[at + 1] - g) <= 4 && Math.abs(data[at + 2] - b) <= 4) count++;
      return count / (dpr * dpr);
    },
    [colour, box] as [number[], typeof box],
  );
}

/** The box of the first picture on the canvas, CSS pixels, as its anchor says (no scrolling, no frozen panes). */
async function frameOf(page: Page, id = 0): Promise<{ x: number; y: number; width: number; height: number }> {
  const anchor = (await pictures(page)).find((picture) => picture.id === id).anchor;
  const x = (marker: any) => HEADER_WIDTH + marker.col * COLUMN_WIDTH + marker.colOff / EMU;
  const y = (marker: any) => HEADER_HEIGHT + marker.row * ROW_HEIGHT + marker.rowOff / EMU;
  if (anchor.kind === 'twoCell') return { x: x(anchor.from), y: y(anchor.from), width: x(anchor.to) - x(anchor.from), height: y(anchor.to) - y(anchor.from) };
  if (anchor.kind === 'oneCell') return { x: x(anchor.from), y: y(anchor.from), width: anchor.width / EMU, height: anchor.height / EMU };
  return { x: HEADER_WIDTH + anchor.x / EMU, y: HEADER_HEIGHT + anchor.y / EMU, width: anchor.width / EMU, height: anchor.height / EMU };
}

async function canvasBox(page: Page): Promise<{ x: number; y: number }> {
  const box = await page.locator('#host .bym-canvas').boundingBox();
  if (!box) throw new Error('the canvas has no box');
  return box;
}

function key(page: Page, init: KeyboardEventInit): Promise<boolean> {
  return page.evaluate((init) => {
    const event = new KeyboardEvent('keydown', { bubbles: true, cancelable: true, ...init });
    document.querySelector('#host .bym-input')!.dispatchEvent(event);
    return event.defaultPrevented;
  }, init);
}

function touchEvent(page: Page, type: string, x: number, y: number, id = 41): Promise<void> {
  return page.evaluate(
    ([type, x, y, id]) => {
      document
        .querySelector('#host .bym-canvas')!
        .dispatchEvent(new PointerEvent(type as string, { pointerId: id as number, pointerType: 'touch', isPrimary: true, clientX: x as number, clientY: y as number, bubbles: true, cancelable: true }));
    },
    [type, x, y, id] as [string, number, number, number],
  );
}

