/** A clipboard event in the grid of an editor (`host` or `host2`): what the view put on the clipboard (copy, cut), or what it is given to paste. */
function clipboard(page: Page, type: 'copy' | 'cut' | 'paste', give?: { text: string; html: string }, host = 'host'): Promise<{ text: string; html: string }> {
  return page.evaluate(
    ([type, text, html, host]) => {
      const data = new DataTransfer();
      if (text !== null) data.setData('text/plain', text);
      if (html !== null) data.setData('text/html', html);
      let event: Event | undefined;
      try {
        event = new ClipboardEvent(type as string, { clipboardData: data, bubbles: true, cancelable: true });
      } catch {
        event = undefined;
      }
      // Some browsers give a scripted clipboard event a clipboard of their own instead of the one passed in.
      if (!event || (event as ClipboardEvent).clipboardData !== data) {
        event = new Event(type as string, { bubbles: true, cancelable: true });
        Object.defineProperty(event, 'clipboardData', { value: data });
      }
      document.querySelector(`#${host} .bym-input`)!.dispatchEvent(event);
      return { text: data.getData('text/plain'), html: data.getData('text/html') };
    },
    [type, give ? give.text : null, give ? give.html : null, host] as [string, string | null, string | null, string],
  );
}

const menuItem = (page: Page, name: string) => page.locator('#host .bym-menu').getByRole('menuitem', { name, exact: true });

/** Opens the menu of the picture whose frame is `frame` (canvas pixels). */
async function openMenu(page: Page, frame: { x: number; y: number; width: number; height: number }): Promise<void> {
  const box = await canvasBox(page);
  await page.mouse.click(box.x + frame.x + frame.width / 2, box.y + frame.y + frame.height / 2, { button: 'right' });
  await expect(page.locator('#host .bym-menu')).toBeVisible();
}

