// and up are functions of Excel 2007 and later, which only later writers use.

const NAMES: string[] = [];

/** The names of a run of consecutive indexes. */
function add(first: number, names: string): void {
  const list = names.split(' ');
  for (let i = 0; i < list.length; i++) NAMES[first + i] = list[i];
}

