/** Name of the built-in function with this index; undefined for an index that is not in use. */
export function functionName(index: number): string | undefined {
  return NAMES[index];
}

/**
 * Number of arguments of a function that PtgFunc may name; undefined for a function that takes
 * a varying number (those are written with PtgFuncVar) and for macro sheet commands.
 */
export function fixedArgCount(index: number): number | undefined {
  const name = NAMES[index];
  return name === undefined ? undefined : FIXED.get(name);
}
